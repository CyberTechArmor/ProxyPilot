// The end-to-end contract for "the apps it builds are well made and lean on
// the base app".
//
// Three reported failures drive this file:
//   1. the shipped app had none of the base app's new features,
//   2. its UI/UX was poor,
//   3. the mockup preview didn't work.
//
// (1) happened because the build prompt never mentioned src/platform, and
// because a project seeded before a feature existed could never receive it.
// (2) happened because the default path — MVP build, then quick updates —
// ran a gate battery of literally ZERO. (3) happened because every failure
// path answered an iframe with JSON.
//
// THE LOAD-BEARING TEST in here is the last one: a FRESHLY SCAFFOLDED app,
// generated by the real scaffold functions, must pass every gate in the MVP
// profile. If it does not, every new project starts red and the gates get
// switched off instead of the app getting fixed.
//
// Native-free (risk R9) apart from running the gate scripts under /bin/sh,
// which is what the container does with them.

