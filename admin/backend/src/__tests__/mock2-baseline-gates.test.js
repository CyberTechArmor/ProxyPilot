test('both prompt builders carry the platform contract — they cannot drift apart', () => {
  const system = buildRunnerSystemPrompt({ constitution: 'C', skills: [], buildMode: 'mvp' });
  const claudeMd = buildRunnerClaudeMd({ constitution: 'C', skills: [] });
  for (const [label, text] of [['system prompt', system], ['CLAUDE.md', claudeMd]]) {
    assert.ok(text.includes(PLATFORM_SECTION), `${label} embeds the shared section verbatim`);
    // The capabilities a build was silently discarding.
    for (const capability of ['theme.js', 'branding', 'legal', 'withApiKey', 'readonly.ts', '/api/meta']) {
      assert.ok(text.includes(capability), `${label} names ${capability}`);
    }
    assert.match(text, /NEVER delete it, re-implement it/, `${label} states the rule`);
    assert.ok(text.includes('platform-intact'), `${label} names the gate that enforces it`);
  }
});

// ---- fix 2: profiles — no build mode runs zero gates ----

test('profiles are cumulative and no mode runs an empty battery', () => {
  assert.ok(tierRank('quick') < tierRank('mvp'));
  assert.ok(tierRank('mvp') < tierRank('full'));
  assert.equal(tierRank('nonsense'), tierRank('full') + 1, 'an unknown tier is stricter than full, never looser');

  const quick = baselineGatesForProfile('quick').map((g) => g.name);
  const mvp = baselineGatesForProfile('mvp').map((g) => g.name);
  const full = baselineGatesForProfile('full').map((g) => g.name);
  for (const n of quick) assert.ok(mvp.includes(n), `${n} carries from quick into mvp`);
  for (const n of mvp) assert.ok(full.includes(n), `${n} carries from mvp into full`);
  assert.deepEqual(full.sort(), [...BASELINE_GATE_NAMES].sort(), 'full runs every baseline gate');

  for (const mode of [BUILD_MODE_QUICK, BUILD_MODE_MVP, BUILD_MODE_FULL]) {
    assert.ok(buildGateBattery([], mode).gates.length > 0, `${mode} runs at least one gate with NO framework gates`);
  }
});

test('gate tiering: declared wins, then the name, then full-only', () => {
  assert.equal(gateTier({ name: 'anything', tier: 'quick' }), 'quick', 'a declared tier wins');
  assert.equal(gateTier({ name: 'typecheck' }), 'quick');
  assert.equal(gateTier({ name: 'tsc' }), 'quick');
  assert.equal(gateTier({ name: 'ui-interaction' }), 'mvp');
  assert.equal(gateTier({ name: 'smoke' }), 'mvp');
  // The safe default: an operator's untagged four-minute check never lands in
  // the fast lanes just because nobody filled a field in.
  assert.equal(gateTier({ name: 'security-scan' }), 'full');
  assert.equal(gateTier({ name: 'some-bespoke-thing' }), 'full');
  assert.equal(gateProfileForMode('nonsense'), 'full', 'an unknown mode gets the strictest profile');
});

