// ---- the gates themselves, run for real ----

const GOOD_PLATFORM = () => {
  const files = {};
  for (const f of [...buildPlatformFiles(), ...buildPlatformRoutes()]) files[f.path] = f.content;
  files['src/app.ts'] = 'import { publicPlatformRoutes, platformRoutes, adminPlatformRoutes } from "./platform/routes.js";\n'
    + 'import { withApiKey } from "./platform/api-key-auth.js";\n';
  files['src/server.ts'] = 'import { ensureSeeded } from "./platform/branding.js";\n'
    + 'import { ensureViews } from "./platform/readonly.js";\nawait ensureSeeded(); await ensureViews();\n';
  files['public/app-shell.html'] = '<!doctype html><html><head><meta name="viewport" content="width=device-width,initial-scale=1">'
    + '<script src="/theme.js"></script></head><body><button id="go">Go</button></body></html>';
  return files;
};

test('GATE platform-intact: catches deletion, unmounting, a parallel store, and an unthemed page', () => {
  // Deleted.
  const gone = GOOD_PLATFORM(); delete gone['src/platform/readonly.ts'];
  const r1 = runScript(PLATFORM_INTACT_GATE_SCRIPT, gone);
  assert.equal(r1.code, 1);
  assert.match(r1.out, /lost files.*readonly\.ts/s);

  // Present but unmounted.
  const unmounted = GOOD_PLATFORM();
  unmounted['src/app.ts'] = '// nothing mounted here\n';
  const r2 = runScript(PLATFORM_INTACT_GATE_SCRIPT, unmounted);
  assert.equal(r2.code, 1);
  assert.match(r2.out, /no longer mounts/);

  // A second store for something the platform owns.
  const dup = GOOD_PLATFORM();
  dup['src/schema.ts'] = 'export const branding = pgTable("branding", { id: text("id") });\n';
  const r3 = runScript(PLATFORM_INTACT_GATE_SCRIPT, dup);
  assert.equal(r3.code, 1);
  assert.match(r3.out, /second store/);

  // A new page that will not theme.
  const unthemed = GOOD_PLATFORM();
  unthemed['public/reports.html'] = '<!doctype html><html><head><meta name="viewport" content="width=device-width"></head><body>x</body></html>';
  const r4 = runScript(PLATFORM_INTACT_GATE_SCRIPT, unthemed);
  assert.equal(r4.code, 1);
  assert.match(r4.out, /does not load \/theme\.js/);

  // An export the rest of the app imports.
  const noExport = GOOD_PLATFORM();
  noExport['src/platform/api-key-auth.ts'] = '// the exports are gone\n';
  const r5 = runScript(PLATFORM_INTACT_GATE_SCRIPT, noExport);
  assert.equal(r5.code, 1);
  assert.match(r5.out, /no longer exports withApiKey/);
});

