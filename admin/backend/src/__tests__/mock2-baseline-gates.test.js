test('the MVP battery CATCHES the app that shipped badly', () => {
  // The composite of every reported failure in one tree: the platform module
  // half-deleted, a parallel palette, a desktop-only width, and a dead button.
  const bad = GOOD_PLATFORM();
  delete bad['src/platform/readonly.ts'];
  bad['state/design.css'] = ':root{'
    + Array.from({ length: 20 }, (_, i) => `--app-t${i}:#10${i}`).join(';')
    + '}[data-theme="dark"]{--app-t0:#000}';
  bad['public/app.css'] = `:root{${Array.from({ length: 32 }, (_, i) => `--own-${i}:#ab${i}`).join(';')}}\n`
    + '.shell{width:1280px}\n'
    + Array.from({ length: 400 }, (_, i) => `.c${i}{color:var(--own-1);padding:8px}`).join('\n');
  bad['public/reports.html'] = '<!doctype html><html><head></head><body><button>Export</button></body></html>';

  const failed = [];
  for (const gate of buildGateBattery([], BUILD_MODE_MVP).gates) {
    if (runScript(gate.script, bad).code !== 0) failed.push(gate.name);
  }
  assert.deepEqual(failed.sort(), ['design-adherence', 'mobile-overflow', 'no-dead-controls', 'platform-intact']);
});

