// ---- fix 3: the mockup preview says why, instead of rendering a JSON blob ----

test('preview failures render a readable HTML card, not JSON', () => {
  for (const key of ['offline', 'none', 'unreadable']) {
    const e = PREVIEW_ERRORS[key];
    const html = previewErrorCard(e);
    assert.match(html, /^<!doctype html>/, `${key} is a document the iframe can render`);
    assert.ok(html.includes(e.title), `${key} states what happened`);
    assert.ok(html.includes(e.detail), `${key} says what to do about it`);
    // It renders in a pane that is regularly 390px wide.
    assert.match(html, /name="viewport"/, `${key} is phone-safe`);
    assert.ok(!/width:\s*\d{3,}px/.test(html), `${key} has no fixed width`);
    // Not JSON — that was the bug.
    assert.ok(!html.trim().startsWith('{'), `${key} is not a JSON blob`);
  }
  assert.equal(PREVIEW_ERRORS.offline.status, 409, 'the status stays honest for programmatic callers');
  assert.equal(PREVIEW_ERRORS.none.status, 404);
});

test('a container error string is escaped into the card, never interpolated raw', () => {
  const html = previewErrorCard({
    title: 'The mockup could not be read',
    detail: 'cat: <script>alert(1)</script> & "quoted"',
  });
  assert.ok(!html.includes('<script>alert(1)</script>'));
  assert.ok(html.includes('&lt;script&gt;'));
  assert.equal(escapePreviewHtml(`<a href="x">&'`), '&lt;a href=&quot;x&quot;&gt;&amp;&#39;');
});
