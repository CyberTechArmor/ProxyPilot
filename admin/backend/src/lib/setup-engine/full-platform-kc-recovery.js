// Keycloak bootstrap-administrator recovery (3h).
//
// connect_managed_identity authenticates as the temporary bootstrap
// administrator Keycloak created from KC_BOOTSTRAP_ADMIN_* on its first start.
// When that account can no longer authenticate (its password was changed or
// it was removed in the console), the only way out used to be a purge. This
// is the supported recovery for the pinned Keycloak 26.x: `kc.sh
// bootstrap-admin user` run inside the OWNED server container creates a new
// temporary master-realm administrator against the same database. The new
// credential is generated here, stored protected (encrypted under the
// installation key) BEFORE it is used, handed to the container only through
// a 0600 env file that is removed right after, verified by an actual token
// grant, and then becomes the bootstrap reference the coordinator uses. The
// coordinator resumes in the same job. Human-confirmed: the dashboard
// (fresh local proof) or recover_keycloak_bootstrap (confirmation token).
//
// The original `bootstrap-admin` account is left in place; retiring the
// bootstrap (step 4) removes both it and the recovery account.

import { randomBytes } from 'node:crypto';
import { join } from 'node:path';
import { existsSync, rmSync } from 'node:fs';
import { readFullPlatform, installedTargets, digest, fail } from './full-platform-store.js';
import { createJob, getJob, jobView } from './store.js';
import { protectedValue, storeProtected, keycloakAdmin } from './full-platform-keycloak.js';
import { keycloakFetch } from '../sso/oidc.js';
import { resourceNames, KEYCLOAK_ROOT } from './keycloak-logic.js';
import { atomicPrivate } from './pomerium-runtime.js';
import { withKeycloakLease } from './full-platform-admin.js';

export const BOOTSTRAP_AUTH_FAILURE = /bootstrap administrator cannot authenticate/i;
const OPEN = ['queued', 'running'];
const stagingRef = (id) => `keycloak-bootstrap-recovery-${id}`;

/** Preconditions + review token. Never throws for a precondition: it lists blockers. */
export function recoveryReview(db) {
  const full = readFullPlatform(db);
  if (!full) throw fail('No Full Platform setup is saved.');
  const k = installedTargets(db).keycloak;
  const blockers = [];
  if (!k || k.mode !== 'install') blockers.push('Only an owned (managed) Keycloak installation can be recovered here; an external Keycloak is recovered by its owner.');
  if (full.approved_revision !== full.revision) blockers.push('Apply the saved Full Platform revision first.');
  const last = full.last_job_id && getJob(db, full.last_job_id);
  if (last && OPEN.includes(last.status)) blockers.push(`Operation ${last.id} is ${last.status}. Wait for it.`);
  const failed = last && !OPEN.includes(last.status) && BOOTSTRAP_AUTH_FAILURE.test(String(last.reason || ''));
  if (!failed) blockers.push('Recovery is offered only after connect_managed_identity recorded that the bootstrap administrator cannot authenticate. The latest operation did not.');
  let retired = false;
  try { const ref = full.state?.identity?.bootstrapRef; retired = !!(ref && protectedValue(db, ref).retired); } catch { /* no reference yet */ }
  if (retired) blockers.push('The bootstrap account was already retired in favour of the permanent administrator; sign in with that administrator instead.');
  const kc = k?.row || null;
  const reviewToken = digest(['keycloak_recovery', full.revision, kc?.id || null, last?.id || null, blockers]);
  return {
    revision: full.revision, installation: kc?.id || null, container: kc ? resourceNames(kc.id).server : null, failed_job: last ? last.id : null, blockers, reviewToken,
    effects: [
      'Runs `kc.sh bootstrap-admin user` inside the owned Keycloak server container to create a new temporary master-realm administrator (Keycloak 26 supported recovery).',
      'The new credential is generated by ProxyPilot, stored encrypted before use, passed to the container only through a private env file that is deleted immediately, and never shown or logged.',
      'The realm, its users, clients and data are not changed. The old bootstrap account is left in place until the bootstrap is retired in step 4.',
      'The saved setup then continues from connect_managed_identity in the same operation.',
    ],
  };
}

export function queueRecovery(db, { revision, reviewToken, reviewed }, by, { via = 'ui' } = {}) {
  if (reviewed !== true) throw fail('Review the Keycloak recovery first.');
  db.exec('BEGIN IMMEDIATE');
  try {
    const full = readFullPlatform(db), review = recoveryReview(db);
    if (!full || Number(revision) !== full.revision || reviewToken !== review.reviewToken) throw fail('The recovery preview is stale. Review it again.', 'RECOVERY_REVIEW_STALE');
    if (review.blockers.length) throw fail(review.blockers.join(' '), 'RECOVERY_BLOCKED');
    const job = createJob(db, { app: 'pp-full-platform', kind: 'full_platform_apply', plan: { params: { revision: full.revision, operation: 'keycloak_recovery' } }, requestedBy: by, via, retryOf: full.last_job_id, reason: 'Reviewed Keycloak bootstrap-administrator recovery, then continue the saved setup.' });
    const state = { ...full.state, keycloakRecovery: { reviewToken, requestedAt: new Date().toISOString() } };
    db.prepare('UPDATE setup_full_platform SET state_json=?,last_job_id=? WHERE id=1').run(JSON.stringify(state), job.id);
    db.exec('COMMIT');
    return { job: jobView(job), created: true };
  } catch (e) { db.exec('ROLLBACK'); throw e; }
}

/** Runner side. Resolves when the recovered credential authenticates; the caller then continues the coordinator. */
export async function runKeycloakRecovery(db, full, job, exec, { root = KEYCLOAK_ROOT, send, admin = keycloakAdmin } = {}) {
  const k = installedTargets(db).keycloak?.row;
  if (!k || k.ownership !== 'managed') throw fail('Only an owned Keycloak installation can be recovered.');
  send ||= keycloakFetch(db, k.origin);
  const bootstrapRef = full.state?.identity?.bootstrapRef || `keycloak-bootstrap-${k.id}`;
  return withKeycloakLease(db, job, async (guarded) => {
    job.checkpoint('keycloak_bootstrap_recovery', { resumable: true });
    const tryAuth = async (c) => { try { const a = await admin(k, c.password, { username: c.username, job: guarded, send }); await a.close(); return true; } catch (e) { if (['FENCED', 'CANCELLED'].includes(e?.code)) throw e; return false; } };
    let staged = null;
    try { staged = protectedValue(db, stagingRef(k.id)); } catch { staged = null; }
    // A previous attempt may have created the account and then been interrupted.
    if (!(staged && await tryAuth(staged))) {
      staged = { username: `pp-recovery-${Date.now().toString(36)}`, password: randomBytes(32).toString('base64url'), installationId: k.id, createdAt: new Date().toISOString() };
      guarded.fence(); storeProtected(db, stagingRef(k.id), staged);
      const envFile = join(root, k.id, `recovery-${randomBytes(4).toString('hex')}.env`);
      const server = resourceNames(k.id).server;
      try {
        guarded.fence(); atomicPrivate(envFile, `PP_RECOVERY_USERNAME=${staged.username}\nPP_RECOVERY_PASSWORD=${staged.password}\n`);
        const base = ['docker', 'exec', '--env-file', envFile, server, '/opt/keycloak/bin/kc.sh', 'bootstrap-admin', 'user', '--username:env', 'PP_RECOVERY_USERNAME', '--password:env', 'PP_RECOVERY_PASSWORD', '--no-prompt'];
        // The running server already built its optimized configuration; reuse it,
        // and fall back to a plain run on an image that was never built.
        let r = await exec.host([...base, '--optimized'], { timeoutMs: 300000 });
        guarded.fence();
        if (r.code !== 0) { r = await exec.host(base, { timeoutMs: 300000 }); guarded.fence(); }
        if (r.code !== 0) throw fail(`kc.sh bootstrap-admin did not complete in ${server} (docker exit ${r.code}). Nothing in the realm was changed; check the Keycloak server container's logs and retry the recovery.`);
      } finally { try { if (existsSync(envFile)) rmSync(envFile, { force: true }); } catch { /* removed on the next attempt */ } }
      if (!(await tryAuth(staged))) throw fail('The recovered bootstrap administrator did not authenticate. The new credential is kept protected for a retry; no realm data changed.');
    }
    guarded.fence();
    const prior = (() => { try { return protectedValue(db, bootstrapRef); } catch { return {}; } })();
    storeProtected(db, bootstrapRef, { ...prior, installationId: k.id, username: staged.username, password: staged.password, retired: false, recovered: job.id, previousUsername: prior.username || 'bootstrap-admin' });
    db.prepare('DELETE FROM setup_full_credentials WHERE id=?').run(stagingRef(k.id));
    const current = readFullPlatform(db), state = { ...current.state }; delete state.keycloakRecovery;
    state.identity = { ...(state.identity || {}), bootstrapRef };
    db.prepare('UPDATE setup_full_platform SET state_json=? WHERE id=1 AND last_job_id=?').run(JSON.stringify(state), job.id);
    return { recovered: true, username: staged.username };
  });
}
