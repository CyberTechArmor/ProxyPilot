// The Infisical administrator's generated password, kept in OpenBao (docs/features/guided-infisical.md
// § "Generated administrator password"). The free edition has no SSO, so the
// person signs in to Infisical with a local password: ProxyPilot generates a
// long one and writes it to the OpenBao team area, where a Keycloak passkey
// sign-in reads it. ProxyPilot keeps no copy; each read or write uses a
// transient root token (withTransientRoot) that is revoked and proved revoked.
import { randomInt } from 'node:crypto';
import { readOpenBao } from './openbao-store.js';
import { autoCustody, namesFor } from './openbao-logic.js';
import { requireReady } from './openbao-api.js';
import { reachableStatus, withTransientRoot } from './openbao-custody.js';
import { infisicalError as fail } from './infisical-logic.js';

export const ADMIN_SECRET_PATH = 'team/infisical-administrator';
const NOTE = 'Generated by ProxyPilot for the Infisical administrator. If you change it in Infisical, save the new one here too.';
const ALPHABET = 'ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz23456789';

// Four groups of six (about 140 bits), easy to copy on a phone, always with an
// upper-case letter, a lower-case letter and a digit.
export function generatePassword(pick = randomInt) {
  for (;;) {
    const value = Array.from({ length: 4 }, () => Array.from({ length: 6 }, () => ALPHABET[pick(ALPHABET.length)]).join('')).join('-');
    if (/[A-Z]/.test(value) && /[a-z]/.test(value) && /[0-9]/.test(value)) return value;
  }
}

// Where the dashboard tells the person to look; null when OpenBao cannot hold it.
const locationOf = b => autoCustody(b) && b.bootstrap_complete ? { engine: `${namesFor(b).prefix}-kv`, path: ADMIN_SECRET_PATH } : null;
export const adminPasswordLocation = db => locationOf(readOpenBao(db));
export const vaultReady = db => !!adminPasswordLocation(db);

// fresh: generate a new password and store it as the next version (bootstrap of
// a new Infisical). Otherwise read the stored one back for a resume sign-in.
export async function infisicalAdminVault(db, { email, origin, fresh, password: chosen = null }, { read = readOpenBao, reach = reachableStatus, ready = requireReady, root = withTransientRoot, generate = generatePassword } = {}) {
  const b = read(db);
  if (!locationOf(b)) throw fail('The generated Infisical password is kept in OpenBao, which is not installed here with automatic custody yet. Finish OpenBao first, or enter a password yourself.');
  const kv = `${namesFor(b).prefix}-kv`, data = `/v1/${kv}/data/${ADMIN_SECRET_PATH}`;
  try {
    const { api } = await reach(db, b);
    await ready(api, b);
    return await root(db, b, api, async token => {
      const current = await api(data, { token });
      if (![200, 404].includes(current.status)) throw fail(`OpenBao could not read ${kv}/${ADMIN_SECRET_PATH} (HTTP ${current.status}).`);
      const stored = current.status === 200 ? current.body?.data?.data : null;
      if (!fresh) {
        if (!stored?.password) throw fail(`No generated Infisical password is stored in OpenBao (${kv}/${ADMIN_SECRET_PATH}). If the account was created with a password you chose, enter that password; otherwise restore the secret from its OpenBao version history.`);
        if (stored.email !== email) throw fail(`The password stored in OpenBao belongs to ${stored.email || 'another account'}, not the recorded Infisical administrator ${email}. Nothing was changed.`);
        return stored.password;
      }
      // Check-and-set on the current version: a concurrent writer fails this
      // write instead of being overwritten. A deleted latest version still counts.
      let version = current.body?.data?.metadata?.version || 0;
      if (current.status === 404) { const meta = await api(`/v1/${kv}/metadata/${ADMIN_SECRET_PATH}`, { token }); version = meta.status === 200 ? meta.body?.data?.current_version || 0 : 0; }
      // A password the person chose is stored as given; otherwise one is generated.
      const password = chosen ?? generate();
      const write = await api(data, { method: 'POST', token, body: { options: { cas: version }, data: { email, password, url: origin, note: NOTE } } });
      if (![200, 204].includes(write.status)) throw fail(`OpenBao did not accept the generated Infisical password (HTTP ${write.status}). Infisical was not initialized.`);
      const back = await api(data, { token });
      if (back.status !== 200 || back.body?.data?.data?.password !== password) throw fail('The generated Infisical password could not be read back from OpenBao. Infisical was not initialized.');
      return password;
    });
  } catch (e) {
    // OpenBao's own refusals are safe to show; say where they came from.
    if (e?.openbaoSafe) throw fail(`OpenBao: ${e.message}`);
    throw e;
  }
}
